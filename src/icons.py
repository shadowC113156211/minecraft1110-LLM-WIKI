# 特定圖示的固定色
FIXED = {"o": "#1d1d1d", "h": "#9c6b30", "H": "#5f3f1a", "g": "#f5cf3b", "r": "#d33a2c", "e": "#3fae3f", "x": "#9a9a9a", "w": "#ffffff"}


def _shade(hexc, f):
    hexc = hexc.lstrip("#")
    r, g, b = [int(hexc[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    l = max(0, min(1, l * f if f < 1 else l + (1 - l) * (f - 1)))
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return "#%02x%02x%02x" % (int(r * 255), int(g * 255), int(b * 255))


def svg(name, color, size=48, title=None):
    rows = T.get(name, T["block"])
    pal = dict(FIXED)
    pal.update({"a": color, "b": _shade(color, 1.45), "c": _shade(color, 0.62)})
    rects = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            run = 1
            while x + run < len(row) and row[x + run] == ch:
                run += 1
            rects.append(f'<rect x="{x}" y="{y}" width="{run}" height="1" fill="{pal.get(ch, color)}"/>')
            x += run
    t = f"<title>{title}</title>" if title else ""
    return (f'<svg class="px" viewBox="0 0 12 12" width="{size}" height="{size}" shape-rendering="crispEdges" '
            f'xmlns="http://www.w3.org/2000/svg" aria-hidden="{ "false" if title else "true"}">{t}{"".join(rects)}</svg>')


HEART_FULL = ['..oo.oo..', '.orroboo.', 'orrrrrwbo', 'orrrrrrro', '.orrrrro.', '..orrro..', '...oro...', '....o....']


def heart(kind="full", size=14):
    pal = {"o": "#1d1d1d", "r": "#d8261f" if kind != "empty" else "#3a3a3a", "w": "#ffb3b3" if kind != "empty" else "#555", "b": "#ff6b6b" if kind != "empty" else "#444"}
    rects = []
    for y, row in enumerate(HEART_FULL):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            col = pal[ch]
            if kind == "half" and x >= 4 and ch in "rwb":
                col = "#3a3a3a"
            rects.append(f'<rect x="{x}" y="{y}" width="1" height="1" fill="{col}"/>')
    return f'<svg class="heart" viewBox="0 0 9 8" width="{size}" height="{int(size*8/9)}" shape-rendering="crispEdges">{"".join(rects)}</svg>'
